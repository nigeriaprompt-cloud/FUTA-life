#!/usr/bin/env python3
"""Generate public/world/game/avatar/avatar-options.js from avatar-options.json (single source of truth)."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.json')
out = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.js')
d = json.load(open(src))
js = "/* GENERATED by tools/build-options.py from avatar-options.json — do not edit by hand. */\n(function(g){var FA=g.FutaAvatar=g.FutaAvatar||{};FA.OPTIONS=" + json.dumps(d, separators=(',', ':')) + ";})(typeof window!=='undefined'?window:globalThis);\n"
open(out, 'w').write(js)
print('wrote', os.path.relpath(out), len(js), 'bytes')

# Also emit the SQL seed so the Supabase validator uses the very same options (single source of truth).
sql_out = os.path.join(here, '..', 'supabase', '02_avatar_options.sql')
body = json.dumps(d, separators=(',', ':')).replace("'", "''")
sql = "-- GENERATED by tools/build-options.py from avatar-options.json — do not edit by hand. Run AFTER 01_schema.sql, and again whenever options change.\ninsert into public.app_config (key, value) values ('avatar_options', '" + body + "'::jsonb)\non conflict (key) do update set value = excluded.value;\n"
open(sql_out, 'w').write(sql)
print('wrote', os.path.relpath(sql_out), len(sql), 'bytes')

# ---- Activities: interior/activities.json -> browser catalog (interior/activities.js) + server catalog (supabase/03_activities.sql)
act_src = os.path.join(here, '..', 'public', 'world', 'game', 'interior', 'activities.json')
if os.path.exists(act_src):
    A = json.load(open(act_src))
    cat = {a['id']: {k: v for k, v in a.items()} for a in A['activities']}
    js_out = os.path.join(here, '..', 'public', 'world', 'game', 'interior', 'activities.js')
    js = "/* GENERATED by tools/build-options.py from activities.json — do not edit by hand. */\n(function(g){g.FutaActs=g.FutaActs||{};g.FutaActs.data=" + json.dumps({'stats': A['stats'], 'decay': A['decay'], 'activities': A['activities']}, separators=(',', ':')) + ";})(typeof window!=='undefined'?window:globalThis);\n"
    open(js_out, 'w').write(js); print('wrote', os.path.relpath(js_out), len(js), 'bytes')
    q = lambda s: "'" + str(s).replace("'", "''") + "'"
    rows = []
    for a in A['activities']:
        arr = "array[" + ",".join(q(v) for v in a['venues']) + "]::text[]"
        rows.append("  (%s, %d, %d, %d, %d, %d, %d, %d, %s, %s)" % (q(a['id']), a.get('secs', 3), a.get('energy', 0), a.get('hunger', 0), a.get('mood', 0), a.get('knowledge', 0), a.get('cash', 0), a.get('cooldown', 0), q(a.get('ui') or ''), arr))
    sql = """-- GENERATED by tools/build-options.py from public/world/game/interior/activities.json — do not edit by hand.
-- Run AFTER 01_schema.sql (and again whenever activities.json changes). The server, not the browser, applies every effect.
create table if not exists public.activities (
  id text primary key, secs int not null, energy int not null default 0, hunger int not null default 0, mood int not null default 0,
  knowledge int not null default 0, cash int not null default 0, cooldown int not null default 0, ui text not null default '', venues text[] not null
);
alter table public.activities enable row level security;
delete from public.activities where id <> all (array[%s]);
insert into public.activities (id, secs, energy, hunger, mood, knowledge, cash, cooldown, ui, venues) values
%s
on conflict (id) do update set secs = excluded.secs, energy = excluded.energy, hunger = excluded.hunger, mood = excluded.mood, knowledge = excluded.knowledge,
  cash = excluded.cash, cooldown = excluded.cooldown, ui = excluded.ui, venues = excluded.venues;

-- Do something inside the building you are standing in (see enter_building). Effects come from the table above.
create or replace function public.do_activity(p_activity text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare u uuid := private.require_user(); a public.activities; s public.player_stats; cd timestamp with time zone; pocket_now bigint;
begin
  select * into a from public.activities where id = p_activity;
  if not found then raise exception 'bad_activity'; end if;
  perform private.require_free(u);                                              -- no activities from a cell
  s := private.decayed_stats(u);
  if s.venue is null or not (s.venue = any (a.venues)) then raise exception 'wrong_place'; end if;
  if a.ui in ('atm') then raise exception 'use_the_atm'; end if;                -- ATM has its own functions
  select last_at into cd from public.activity_cooldowns where user_id = u and activity = a.id;
  if cd is not null and cd > now() - make_interval(secs => a.cooldown) then raise exception 'cooldown'; end if;
  if a.energy < 0 and s.energy + a.energy < 0 then raise exception 'too_tired'; end if;
  if a.cash < 0 then
    select w.pocket into pocket_now from public.wallets w where w.id = u for update;
    if pocket_now < -a.cash then raise exception 'insufficient_funds'; end if;
    perform private.ledger_move(u, 'activity', a.cash, 0, a.id);
  end if;
  update public.player_stats set energy = greatest(0, least(100, energy + a.energy)), hunger = greatest(0, least(100, hunger + a.hunger)),
      mood = greatest(0, least(100, mood + a.mood)), knowledge = knowledge + a.knowledge, updated_at = now() where id = u;
  insert into public.activity_cooldowns (user_id, activity, last_at) values (u, a.id, now())
    on conflict (user_id, activity) do update set last_at = excluded.last_at;
  return public.get_stats();
end $$;

revoke execute on function public.do_activity(text) from public, anon;
grant execute on function public.do_activity(text) to authenticated;
""" % (",".join(q(a['id']) for a in A['activities']), ",\n".join(rows))
    sql_out2 = os.path.join(here, '..', 'supabase', '03_activities.sql')
    open(sql_out2, 'w').write(sql); print('wrote', os.path.relpath(sql_out2), len(sql), 'bytes')
