#!/usr/bin/env python3
"""Generate public/world/game/avatar/avatar-options.js from avatar-options.json (single source of truth)."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.json')
out = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.js')
d = json.load(open(src))
js = "/* GENERATED by tools/build-options.py from avatar-options.json — do not edit by hand. */\n(function(g){var FA=g.FutaAvatar=g.FutaAvatar||{};FA.OPTIONS=" + json.dumps(d, separators=(',', ':')) + ";})(typeof window!=='undefined'?window:globalThis);\n"
open(out, 'w').write(js)
print('wrote', os.path.relpath(out), len(js), 'bytes')
