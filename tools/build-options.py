#!/usr/bin/env python3
"""Generate public/world/game/avatar/avatar-options.js from avatar-options.json (single source of truth)."""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.json')
out = os.path.join(here, '..', 'public', 'world', 'game', 'avatar', 'avatar-options.js')
d = json.load(open(src))
js = "/* GENERATED by tools/build-options.py from avatar-options.json — do not edit by hand. */\n(function(g){var FA=g.FutaAvatar=g.FutaAvatar||{};FA.OPTIONS=" + json.dumps(d, separators=(',', ':')) + ";})(typeof window!=='undefined'?window:globalThis);\n"
open(out, 'w').write(js)
print('wrote', os.path.relpath(out), len(js), 'bytes')

# Also emit the SQL seed so the Supabase validator uses the very same options (single source of truth).
sql_out = os.path.join(here, '..', 'supabase', '02_avatar_options.sql')
body = json.dumps(d, separators=(',', ':')).replace("'", "''")
sql = "-- GENERATED by tools/build-options.py from avatar-options.json — do not edit by hand. Run AFTER 01_schema.sql, and again whenever options change.\ninsert into public.app_config (key, value) values ('avatar_options', '" + body + "'::jsonb)\non conflict (key) do update set value = excluded.value;\n"
open(sql_out, 'w').write(sql)
print('wrote', os.path.relpath(sql_out), len(sql), 'bytes')
